def choose_remote_access(settings: Settings, existing: Mapping[str, str], assume_yes: bool, remote: str | None) -> None:
    if remote:
        mode = normalize_remote_mode(remote)
        if mode is None:
            raise SetupError(
                f"Unknown remote access {remote!r}. Use lan, cloudflare, forward, tailscale, or local.\n\n"
                "  ./install.sh --remote lan\n"
                "  ./install.sh --remote cloudflare\n"
                "  ./install.sh --remote forward\n"
                "  ./install.sh --remote tailscale\n"
                "  ./install.sh --remote local"
            )
        settings.remote_access = mode
    elif not assume_yes and can_prompt():
        settings.remote_access = ask_where_to_watch(settings.remote_access or "lan")
    elif "REMOTE_ACCESS" not in existing:
        settings.remote_access = "local"
    else:
        mode = normalize_remote_mode(settings.remote_access)
        if mode is None:
            raise SetupError(
                f"REMOTE_ACCESS={settings.remote_access!r} is not lan, local, cloudflare, forward, or tailscale.\n\n"
                "Edit .env or rerun with --remote lan, --remote cloudflare, --remote forward, --remote tailscale, or --remote local."
            )
        settings.remote_access = mode

    settings.cloudflare_api_token = settings.cloudflare_api_token.strip()
    settings.cloudflare_tunnel_token = settings.cloudflare_tunnel_token.strip()
    if settings.remote_access != "cloudflare":
        return
    interactive = not assume_yes and can_prompt()
    if interactive and not settings.cloudflare_hostname:
        settings.cloudflare_hostname = prompt("Jellyfin hostname (watch.example.com)", "")
    if interactive and not settings.cloudflare_api_token and not settings.cloudflare_tunnel_token:
        settings.cloudflare_api_token = prompt("Cloudflare API token", "", secret=True)
    settings.cloudflare_api_token = settings.cloudflare_api_token.strip()
    settings.cloudflare_tunnel_token = settings.cloudflare_tunnel_token.strip()
    if settings.cloudflare_hostname.strip():
        settings.cloudflare_hostname = normalize_hostname(settings.cloudflare_hostname)
    seerr_name = settings.cloudflare_seerr_hostname.strip()
    if seerr_name and seerr_name.lower() not in {"off", "none", "-"}:
        settings.cloudflare_seerr_hostname = normalize_hostname(seerr_name)
    elif seerr_name:
        settings.cloudflare_seerr_hostname = seerr_name.lower()


def require_cloudflare_credentials(settings: Settings) -> None:
    """Fail before Docker starts when the tunnel was requested and the login is still missing."""
    if settings.remote_access != "cloudflare":
        return
    if not settings.cloudflare_api_token and not settings.cloudflare_tunnel_token:
        raise SetupError(cloudflare_setup_help(settings))
    if settings.cloudflare_api_token and not settings.cloudflare_hostname and not settings.cloudflare_tunnel_token:
        raise SetupError(
            "Cloudflare needs the hostname people will open, such as watch.example.com.\n\n"
            "Rerun with CLOUDFLARE_HOSTNAME='watch.example.com' and the same --remote cloudflare command."
        )


def collect_settings(assume_yes: bool, no_vpn: bool, remote: str | None = None) -> tuple[Settings, dict[str, str]]:
    existing = merged_env()
    settings = Settings.from_mapping(existing)
    if not settings.puid or settings.puid == "1000" and "PUID" not in existing:
        settings.puid = str(os.getuid())
    if not settings.pgid or settings.pgid == "1000" and "PGID" not in existing:
        settings.pgid = str(os.getgid())
    if "TZ" not in existing:
        settings.tz = host_timezone()
    settings.admin_user = prompt("Admin username", settings.admin_user or "admin", assume_yes=assume_yes)
    if not settings.admin_password:
        generated = generate_password()
        settings.admin_password = prompt(
            "Admin password (Jellyfin, Seerr, Sonarr, Radarr, Prowlarr, qBittorrent)",
            generated,
            secret=True,
            assume_yes=assume_yes,
        )
    settings.media_dir = prompt("Media directory", settings.media_dir, assume_yes=assume_yes)
    settings.download_dir = prompt("Download directory", settings.download_dir, assume_yes=assume_yes)
    settings.tz = prompt("Timezone", settings.tz, assume_yes=assume_yes)

    if no_vpn:
        settings.use_vpn = "0"
    elif "USE_VPN" not in existing:
        use_vpn = confirm(
            "Route qBittorrent and Prowlarr through a VPN (Gluetun)",
            default=True,
            assume_yes=assume_yes and bool(settings.openvpn_user or settings.wireguard_private_key),
        )
        # Non-interactive --yes without credentials should not silently skip the VPN.
        if assume_yes and not sys.stdin.isatty() and not (settings.openvpn_user or settings.wireguard_private_key):
            settings.use_vpn = existing.get("USE_VPN", "1")
        else:
            settings.use_vpn = "1" if use_vpn else "0"

    if settings.vpn_enabled:
        settings.vpn_service_provider = prompt(
            "VPN provider (Gluetun name, the guide uses ivpn)",
            settings.vpn_service_provider or "ivpn",
            assume_yes=assume_yes,
        )
        settings.vpn_type = prompt("VPN type (openvpn or wireguard)", settings.vpn_type or "openvpn", assume_yes=assume_yes)
        if settings.vpn_type.lower() == "wireguard":
            settings.wireguard_private_key = prompt(
                "WireGuard private key",
                settings.wireguard_private_key,
                secret=True,
                assume_yes=assume_yes,
            )
            settings.wireguard_addresses = prompt(
                "WireGuard addresses",
                settings.wireguard_addresses,
                assume_yes=assume_yes,
            )
            if not settings.wireguard_private_key or not settings.wireguard_addresses:
                raise SetupError(
                    "WireGuard needs WIREGUARD_PRIVATE_KEY and WIREGUARD_ADDRESSES. "
                    "Set them and rerun, or pass --no-vpn."
                )
        else:
            settings.openvpn_user = prompt("OpenVPN username", settings.openvpn_user, assume_yes=assume_yes)
            settings.openvpn_password = prompt(
                "OpenVPN password",
                settings.openvpn_password,
                secret=True,
                assume_yes=assume_yes,
            )
            if not settings.openvpn_user or not settings.openvpn_password:
                raise SetupError(
                    "The VPN account is the one login this command cannot create for you.\n"
                    "Pass the OpenVPN user from your provider (the guide uses IVPN):\n\n"
                    "  OPENVPN_USER='...' OPENVPN_PASSWORD='...' ./install.sh --yes\n\n"
                    "To run with downloads on the normal network instead:\n\n"
                    "  ./install.sh --yes --no-vpn"
                )
    choose_remote_access(settings, existing, assume_yes, remote)
    return settings, {key: value for key, value in existing.items() if key.startswith("GLUETUN_")}


def docker_command() -> list[str]:
    if shutil.which("docker") is None:
        raise SetupError("Docker is not installed. Re-run ./install.sh so it can install Docker.")
    probe = subprocess.run(["docker", "info"], check=False, capture_output=True, text=True)
    if probe.returncode == 0:
        return ["docker"]
    if shutil.which("sudo"):
        return ["sudo", "docker"]
    raise SetupError(probe.stderr.strip() or "docker info failed")


def compose_up(use_vpn: bool, services: list[str] | None = None) -> None:
    compose_file = ROOT / ("docker-compose.yml" if use_vpn else "docker-compose.novpn.yml")
    if not compose_file.exists():
        compose_file.write_text(render_compose(use_vpn), encoding="utf-8")
    command = docker_command() + ["compose", "-f", str(compose_file), "up", "-d"]
    if not services:
        command.append("--remove-orphans")
    if services:
        command.extend(services)
    subprocess.run(command, check=True, cwd=ROOT)


def restart_service(service: str, use_vpn: bool) -> None:
    compose_file = ROOT / ("docker-compose.yml" if use_vpn else "docker-compose.novpn.yml")
    command = docker_command() + ["compose", "-f", str(compose_file), "restart", service]
    subprocess.run(command, check=True, cwd=ROOT)


