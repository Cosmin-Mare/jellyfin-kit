    def setup_jellyfin(self) -> None:
        client = ApiClient(self.urls["jellyfin"])
        wait_until("Jellyfin", lambda: jellyfin_is_ready(self.urls["jellyfin"]))
        _, public = client.request("GET", "/System/Info/Public")
        completed = bool(public.get("StartupWizardCompleted")) if isinstance(public, dict) else False
        auth_header = (
            'MediaBrowser Client="Jellyfin Installer", Device="installer", '
            'DeviceId="jellyfin-one-command", Version="12.0.0"'
        )
        startup_headers = {"Authorization": auth_header, "X-Emby-Authorization": auth_header}
        if not completed:
            client.request(
                "POST",
                "/Startup/Configuration",
                json_body={
                    "ServerName": "Jellyfin",
                    "UICulture": "en-US",
                    "MetadataCountryCode": "US",
                    "PreferredMetadataLanguage": "en",
                },
                headers=startup_headers,
            )
            self._create_jellyfin_admin(client, startup_headers, auth_header)
            self._add_jellyfin_libraries(client, auth_header, token=None)
            client.request(
                "POST",
                "/Startup/RemoteAccess",
                json_body={"EnableRemoteAccess": True},
                headers=startup_headers,
            )
            client.request("POST", "/Startup/Complete", headers=startup_headers)
        token = self._jellyfin_token(client, auth_header)
        self._add_jellyfin_libraries(client, auth_header, token)

    def _create_jellyfin_admin(self, client: ApiClient, startup_headers: dict[str, str], auth_header: str) -> None:
        """Set the admin password.

        Current Jellyfin creates the first user when GET /Startup/User runs.
        POST /Startup/User returns 404 until that user exists, and 403 once a password is set.
        """
        body = {"Name": self.settings.admin_user, "Password": self.settings.admin_password}
        self._read_jellyfin_first_user(client, startup_headers)
        try:
            client.request("POST", "/Startup/User", json_body=body, headers=startup_headers)
            return
        except SetupError as error:
            if "404" not in str(error):
                if "403" in str(error) or "400" in str(error):
                    self._jellyfin_token(client, auth_header)
                    return
                raise
        self._read_jellyfin_first_user(client, startup_headers)
        try:
            client.request("POST", "/Startup/User", json_body=body, headers=startup_headers)
        except SetupError as error:
            if "403" in str(error) or "400" in str(error):
                self._jellyfin_token(client, auth_header)
                return
            raise

    def _read_jellyfin_first_user(self, client: ApiClient, startup_headers: dict[str, str]) -> None:
        try:
            client.request("GET", "/Startup/User", headers=startup_headers)
        except SetupError as error:
            # Older servers create the user on POST and have no GET.
            if "404" not in str(error):
                raise

    def _jellyfin_token(self, client: ApiClient, auth_header: str) -> str:
        _, auth = client.request(
            "POST",
            "/Users/AuthenticateByName",
            json_body={"Username": self.settings.admin_user, "Pw": self.settings.admin_password},
            headers={"Authorization": auth_header, "X-Emby-Authorization": auth_header},
        )
        if not isinstance(auth, dict) or not auth.get("AccessToken"):
            raise SetupError("Jellyfin did not return an access token for the admin account.")
        return str(auth["AccessToken"])

    def _add_jellyfin_libraries(self, client: ApiClient, auth_header: str, token: str | None) -> None:
        headers = {"Authorization": auth_header, "X-Emby-Authorization": auth_header}
        if token:
            headers["Authorization"] = auth_header + f', Token="{token}"'
            headers["X-Emby-Token"] = token
        try:
            _, existing = client.request("GET", "/Library/VirtualFolders", headers=headers)
        except SetupError:
            if token is None:
                return
            raise
        names = set()
        if isinstance(existing, list):
            names = {str(item.get("Name", "")) for item in existing}
        libraries = (
            ("Movies", "movies", "/media/movies"),
            ("TV", "tvshows", "/media/tv"),
        )
        for name, collection, folder in libraries:
            if name in names:
                continue
            query = urllib.parse.urlencode(
                {
                    "name": name,
                    "collectionType": collection,
                    "paths": folder,
                    "refreshLibrary": "true",
                }
            )
            client.request(
                "POST",
                f"/Library/VirtualFolders?{query}",
                json_body={
                    "LibraryOptions": {
                        "Enabled": True,
                        "EnableRealtimeMonitor": True,
                        "EnableChapterImageExtraction": False,
                        "ExtractChapterImagesDuringLibraryScan": False,
                        "EnableInternetProviders": True,
                        "EnableAutomaticSeriesGrouping": False,
                        "PreferredMetadataLanguage": "en",
                        "MetadataCountryCode": "US",
                        "SeasonZeroDisplayName": "Specials",
                        "AutomaticRefreshIntervalDays": 0,
                        "PathInfos": [{"Path": folder}],
                    }
                },
                headers=headers,
            )

    def setup_qbittorrent(self) -> None:
        client = ApiClient(self.urls["qbit"])
        client.headers["Referer"] = self.urls["qbit"] + "/"
        wait_until("qBittorrent", lambda: service_is_up(self.urls["qbit"] + "/api/v2/app/version"))
        if not self._qbit_login(client, self.settings.admin_password):
            temporary = self._temporary_qbit_password()
            if not temporary or not self._qbit_login(client, temporary):
                raise SetupError(
                    "Could not sign in to qBittorrent with the generated account or the temporary password."
                )
        preferences = {
            "save_path": "/downloads/completed",
            "temp_path_enabled": True,
            "temp_path": "/downloads/incomplete",
            "web_ui_address": "0.0.0.0",
            "web_ui_username": self.settings.admin_user,
            "web_ui_password": self.settings.admin_password,
            "web_ui_host_header_validation_enabled": False,
            "web_ui_domain_list": "*",
            "web_ui_csrf_protection_enabled": False,
            "web_ui_secure_cookie_enabled": False,
            "web_ui_upnp_enabled": False,
        }
        if self.settings.vpn_enabled:
            preferences["current_network_interface"] = "tun0"
            preferences["current_interface_name"] = "tun0"
        client.request(
            "POST",
            "/api/v2/app/setPreferences",
            form={"json": json.dumps(preferences)},
            expected=(200,),
        )
        for category in (TV_CATEGORY, MOVIE_CATEGORY):
            try:
                client.request(
                    "POST",
                    "/api/v2/torrents/createCategory",
                    form={"category": category},
                    expected=(200, 409),
                )
            except SetupError as error:
                if "409" not in str(error):
                    raise

    def _qbit_login(self, client: ApiClient, password: str) -> bool:
        try:
            status, body = client.request(
                "POST",
                "/api/v2/auth/login",
                form={"username": self.settings.admin_user, "password": password},
                expected=(200, 204),
            )
        except SetupError:
            return False
        # qBittorrent 5.2 answers a good login with 204 and an empty body.
        # Older releases answer 200 and the text "Ok."
        if status == 204:
            return True
        return isinstance(body, str) and body.strip().startswith("Ok")

    def _temporary_qbit_password(self) -> str:
        if shutil.which("docker") is None:
            return ""
        try:
            result = subprocess.run(
                ["docker", "logs", "qbittorrent"],
                check=False,
                capture_output=True,
                text=True,
            )
        except OSError:
            return ""
        text = result.stdout + result.stderr
        patterns = (
            r"temporary password is provided for this session:\s*(\S+)",
            r"The WebUI administrator password is:\s*(\S+)",
            r"temporary password[^:\n]*:\s*(\S+)",
        )
        for pattern in patterns:
            match = re.search(pattern, text, flags=re.IGNORECASE)
            if match:
                return match.group(1).strip().strip(".")
        return ""

    def setup_servarr(
        self,
        name: str,
        *,
        root: str,
        category_field: str,
        category: str,
        sync_categories: list[int],
    ) -> None:
        client = self._servarr_client(name)
        self._set_servarr_account(client)
        self._ensure_root(client, root)
        self._enable_rename(client, name)
        self._cap_quality(client, name)
        self._ensure_download_client(client, category_field, category)
        self.api_keys[name] = read_api_key(self.config_dir / name / "config.xml") or client.headers.get(
            "X-Api-Key", ""
        )
        # Stash sync categories for Prowlarr; the schema default is used when present.
        setattr(self, f"_{name}_categories", sync_categories)

    def _servarr_client(self, name: str) -> ApiClient:
        config_xml = self.config_dir / name / "config.xml"
        api_version = "v3" if name in {"sonarr", "radarr"} else "v1"

        def ready() -> bool:
            return bool(read_api_key(config_xml)) and service_is_up(self.urls[name] + "/ping")

        wait_until(name, ready)
        client = ApiClient(self.urls[name])
        client.headers["X-Api-Key"] = read_api_key(config_xml)
        try:
            client.request("GET", f"/api/{api_version}/config/host")
            return client
        except SetupError as error:
            if "401" not in str(error) and "403" not in str(error):
                raise
        self.log(f"{name} rejected the API key until local auth was relaxed. Restarting it...")
        patch_servarr_auth(config_xml)
        try:
            os.chown(config_xml, int(self.settings.puid), int(self.settings.pgid))
        except (OSError, ValueError):
            pass
        if self.restarter:
            self.restarter(name)
        time.sleep(2)
        wait_until(name, ready)

        def authed() -> bool:
            try:
                client.headers["X-Api-Key"] = read_api_key(config_xml)
                client.request("GET", f"/api/{api_version}/config/host")
                return True
            except SetupError:
                return False

        wait_until(f"{name} API", authed)
        return client

    def _set_servarr_account(self, client: ApiClient) -> None:
        version = self._api_version(client)
        _, host = client.request("GET", f"/api/{version}/config/host")
        if not isinstance(host, dict):
            raise SetupError("Host config was not JSON.")
        host["username"] = self.settings.admin_user
        host["password"] = self.settings.admin_password
        host["passwordConfirmation"] = self.settings.admin_password
        host["authenticationMethod"] = "forms"
        host["authenticationRequired"] = "enabled"
        try:
            client.request("PUT", f"/api/{version}/config/host", json_body=host)
        except SetupError:
            host["authenticationMethod"] = "Forms"
            host["authenticationRequired"] = "Enabled"
            client.request("PUT", f"/api/{version}/config/host", json_body=host)

    def _api_version(self, client: ApiClient) -> str:
        if client.base_url == self.urls["prowlarr"]:
            return "v1"
        return "v3"

    def _ensure_root(self, client: ApiClient, path: str) -> None:
        version = self._api_version(client)
        _, folders = client.request("GET", f"/api/{version}/rootfolder")
        existing = {item.get("path") for item in folders} if isinstance(folders, list) else set()
        if path not in existing and path + "/" not in existing:
            client.request("POST", f"/api/{version}/rootfolder", json_body={"path": path}, expected=(200, 201))

    def _enable_rename(self, client: ApiClient, name: str) -> None:
        version = self._api_version(client)
        _, naming = client.request("GET", f"/api/{version}/config/naming")
        if not isinstance(naming, dict):
            return
        if name == "sonarr":
            naming["renameEpisodes"] = True
            naming["replaceIllegalCharacters"] = True
        elif name == "radarr":
            naming["renameMovies"] = True
            naming["replaceIllegalCharacters"] = True
        client.request("PUT", f"/api/{version}/config/naming", json_body=naming)
        _, media = client.request("GET", f"/api/{version}/config/mediamanagement")
        if isinstance(media, dict):
            media["copyUsingHardlinks"] = True
            client.request("PUT", f"/api/{version}/config/mediamanagement", json_body=media)

    def _cap_quality(self, client: ApiClient, name: str) -> None:
        version = self._api_version(client)
        _, profiles = client.request("GET", f"/api/{version}/qualityprofile")
        if not isinstance(profiles, list) or not profiles:
            raise SetupError(f"{name} did not return quality profiles.")
        profile = next((item for item in profiles if item.get("name") == "Any"), profiles[0])
        cap_profile_at_1080(profile)
        client.request("PUT", f"/api/{version}/qualityprofile/{profile['id']}", json_body=profile)
        self.profile_ids[name] = int(profile["id"])

    def _ensure_download_client(self, client: ApiClient, category_field: str, category: str) -> None:
        version = self._api_version(client)
        _, schemas = client.request("GET", f"/api/{version}/downloadclient/schema")
