        initialized = bool(public.get("initialized")) if isinstance(public, dict) else False
        self._login_seerr(client, with_server=not initialized)
        if not initialized:
            self._remember_seerr_external_url(client)
            self._enable_seerr_libraries(client)
        self._add_seerr_service(client, "sonarr", internal_port=8989, directory="/tv")
        self._add_seerr_service(client, "radarr", internal_port=7878, directory="/movies")
