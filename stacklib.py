def prepare_directories(settings: Settings) -> None:
    config_dir = (ROOT / settings.config_dir).resolve()
    media_dir = (ROOT / settings.media_dir).resolve()
    download_dir = (ROOT / settings.download_dir).resolve()
    for path in (
        config_dir,
        config_dir / "jellyfin",
        config_dir / "gluetun",
        config_dir / "qbittorrent",
        config_dir / "prowlarr",
        config_dir / "flaresolverr",
        config_dir / "sonarr",
        config_dir / "radarr",
        config_dir / "seerr",
        media_dir / "tv",
        media_dir / "movies",
        download_dir / "completed",
        download_dir / "incomplete",
    ):
        path.mkdir(parents=True, exist_ok=True)
        _give_to_user(path, settings.puid, settings.pgid)
    write_qbittorrent_conf(config_dir, settings.admin_user, settings.admin_password, settings.vpn_enabled)
    for path in (config_dir, media_dir, download_dir):
        _give_tree_to_user(path, settings.puid, settings.pgid)


def _give_to_user(path: Path, puid: str, pgid: str) -> None:
    try:
        os.chmod(path, 0o775)
        os.chown(path, int(puid), int(pgid))
    except (PermissionError, ValueError):
        if shutil.which("sudo") is None:
            raise
        subprocess.run(["sudo", "chown", f"{puid}:{pgid}", str(path)], check=True)
        subprocess.run(["sudo", "chmod", "775", str(path)], check=True)


def _give_tree_to_user(path: Path, puid: str, pgid: str) -> None:
    try:
        uid = int(puid)
        gid = int(pgid)
    except ValueError:
        return
    needs_sudo = False
    for current, dirs, files_ in os.walk(path):
        try:
            os.chown(current, uid, gid)
            for name in dirs + files_:
                os.chown(Path(current) / name, uid, gid)
        except PermissionError:
            needs_sudo = True
            break
    if needs_sudo and shutil.which("sudo"):
        subprocess.run(["sudo", "chown", "-R", f"{puid}:{pgid}", str(path)], check=True)


class ApiClient:
    def __init__(self, base_url: str, timeout: float = 30) -> None:
        self.base_url = base_url.rstrip("/")
        self.timeout = timeout
        self.cookies = CookieJar()
        self.opener = urllib.request.build_opener(urllib.request.HTTPCookieProcessor(self.cookies))
        self.headers: dict[str, str] = {}

    def request(
        self,
        method: str,
        path: str,
        *,
        json_body: Any = None,
        form: Mapping[str, Any] | None = None,
        expected: Iterable[int] = (200, 201, 202, 204),
        headers: Mapping[str, str] | None = None,
    ) -> tuple[int, Any]:
        url = self.base_url + path
        data = None
        req_headers = {"Accept": "application/json", **self.headers}
        if headers:
            req_headers.update(headers)
        if json_body is not None:
            data = json.dumps(json_body).encode("utf-8")
            req_headers["Content-Type"] = "application/json"
        elif form is not None:
            data = urllib.parse.urlencode(form, doseq=True).encode("utf-8")
            req_headers["Content-Type"] = "application/x-www-form-urlencoded"
        request = urllib.request.Request(url, data=data, headers=req_headers, method=method)
        try:
            with self.opener.open(request, timeout=self.timeout) as response:
                status = response.status
                raw = response.read()
        except urllib.error.HTTPError as error:
            status = error.code
            raw = error.read()
        body: Any = raw.decode("utf-8", errors="replace") if raw else ""
        if body and "application/json" in req_headers.get("Accept", ""):
            try:
                body = json.loads(body)
            except json.JSONDecodeError:
                pass
        if status not in set(expected):
            detail = body if isinstance(body, str) else json.dumps(body)[:800]
            raise SetupError(f"{method} {url} returned {status}: {detail}")
        return status, body


def wait_until(label: str, check: Callable[[], bool], timeout: float = 240, pause: float = 2) -> None:
    deadline = time.time() + timeout
    last_error = "not ready"
    while time.time() < deadline:
        try:
            if check():
                return
        except Exception as error:  # noqa: BLE001 - keep polling through startup races
            last_error = str(error)
        time.sleep(pause)
    raise SetupError(f"Timed out waiting for {label}: {last_error}")


def jellyfin_is_ready(base_url: str) -> bool:
    """Jellyfin serves an HTML splash with 503 until the API answers JSON."""
    try:
        with urllib.request.urlopen(base_url.rstrip("/") + "/System/Info/Public", timeout=5) as response:
            if response.status >= 500:
                return False
            payload = json.loads(response.read().decode("utf-8"))
    except Exception:
        return False
    return isinstance(payload, dict) and "StartupWizardCompleted" in payload


def service_is_up(url: str) -> bool:
    try:
        with urllib.request.urlopen(url, timeout=5) as response:
            return response.status < 500
    except urllib.error.HTTPError as error:
        return error.code < 500
    except Exception:
        return False


def read_api_key(config_xml: Path) -> str:
    if not config_xml.exists():
        return ""
    try:
        root = ET.parse(config_xml).getroot()
    except ET.ParseError:
        return ""
    value = root.findtext("ApiKey") or ""
    return value.strip()


def patch_servarr_auth(config_xml: Path) -> None:
    tree = ET.parse(config_xml)
    root = tree.getroot()
    for tag, value in (
        ("AuthenticationMethod", "External"),
        ("AuthenticationRequired", "DisabledForLocalAddresses"),
    ):
        element = root.find(tag)
        if element is None:
            element = ET.SubElement(root, tag)
        element.text = value
    tree.write(config_xml, encoding="utf-8", xml_declaration=True)


def cap_profile_at_1080(profile: dict[str, Any]) -> dict[str, Any]:
    """Allow qualities up to 1080p and upgrade until the best allowed 1080p."""

    def resolution(item: dict[str, Any]) -> int:
        quality = item.get("quality") or {}
        return int(quality.get("resolution") or 0)

    def quality_name(item: dict[str, Any]) -> str:
        quality = item.get("quality") or {}
        return str(quality.get("name") or item.get("name") or "")

    def walk(items: list[dict[str, Any]]) -> None:
        for item in items:
            children = item.get("items")
            if children:
                walk(children)
                item["allowed"] = any(child.get("allowed") for child in children)
                continue
            name = quality_name(item)
            res = resolution(item)
            if res > 1080 or "2160" in name:
                item["allowed"] = False
            elif res >= 720:
                item["allowed"] = True

    def cutoff(items: list[dict[str, Any]]) -> int | None:
        best_id = None
        best_rank = -1
        for item in items:
            children = item.get("items")
            if children:
                nested = cutoff(children)
                child_res = max((resolution(child) for child in children), default=0)
                rank = child_res + (50 if "bluray" in quality_name(item).lower() else 0)
                if item.get("allowed") and nested is not None and rank >= best_rank and child_res <= 1080:
                    best_id = item.get("id", nested)
                    best_rank = rank
                continue
            if not item.get("allowed"):
                continue
            res = resolution(item)
            if res > 1080:
                continue
            name = quality_name(item).lower()
            rank = res + (50 if "bluray" in name else 0)
            quality_id = (item.get("quality") or {}).get("id")
            if quality_id is not None and rank >= best_rank:
                best_id = quality_id
                best_rank = rank
        return best_id

    items = profile.get("items") or []
    walk(items)
    chosen = cutoff(items)
    profile["upgradeAllowed"] = True
    if chosen is not None:
        profile["cutoff"] = chosen
    return profile


def apply_field_values(fields: list[dict[str, Any]], overrides: Mapping[str, Any]) -> list[dict[str, Any]]:
    lowered = {str(key).lower(): value for key, value in overrides.items()}
    applied = []
    for field in fields:
        name = field["name"]
        value = field.get("value")
        if name.lower() in lowered:
            value = lowered[name.lower()]
        applied.append({"name": name, "value": value})
    return applied


def find_implementation(schemas: list[dict[str, Any]], implementation: str) -> dict[str, Any]:
    for schema in schemas:
        if schema.get("implementation") == implementation:
            return schema
    names = ", ".join(schema.get("implementation", "?") for schema in schemas)
    raise SetupError(f"Could not find {implementation} in schema ({names})")


