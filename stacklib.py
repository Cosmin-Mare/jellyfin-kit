def classify_install(
    config_dir: Path,
    containers: Iterable[str],
    *,
    use_vpn: bool,
    env_exists: bool,
) -> tuple[list[str], list[str]]:
    """Split the stack into what is already on disk and what still needs installing."""
    names = {item.strip().lower() for item in containers}
    present: list[str] = []
    missing: list[str] = []
    if env_exists:
        present.append("Saved settings (.env)")
    for folder, label in APP_PARTS:
        if folder == "gluetun" and not use_vpn:
            continue
        if (config_dir / folder).exists() or folder in names:
            present.append(label)
        else:
            missing.append(label)
    return present, missing


def list_container_names() -> list[str]:
    try:
        command = docker_command()
    except SetupError:
        return []
    result = subprocess.run(
        command + ["ps", "-a", "--format", "{{.Names}}"],
        check=False,
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        return []
    return [line.strip() for line in result.stdout.splitlines() if line.strip()]


def review_existing(settings: Settings, assume_yes: bool) -> bool:
    """Ask before changing config that is already here. Missing apps are still installed."""
    config_dir = Path(settings.config_dir)
    if not config_dir.is_absolute():
        config_dir = ROOT / config_dir
    present, missing = classify_install(
        config_dir,
        list_container_names(),
        use_vpn=settings.vpn_enabled,
        env_exists=ENV_PATH.exists(),
    )
    if not present:
        print("Installing Jellyfin, Seerr, Radarr, Sonarr, Prowlarr, qBittorrent, and FlareSolverr.")
        return True
    print("Already on this computer:")
    for item in present:
        print(f"  {item}")
    if missing:
        print("Still to install:")
        for item in missing:
            print(f"  {item}")
    return confirm(
        "Check the existing config and repair anything that is disconnected",
        default=True,
        assume_yes=assume_yes,
    )


def install(assume_yes: bool, no_vpn: bool, configure_only: bool, remote: str | None = None) -> None:
    settings, extras = collect_settings(assume_yes=assume_yes, no_vpn=no_vpn, remote=remote)
    repair = review_existing(settings, assume_yes=assume_yes)
    write_env_file(ENV_PATH, settings, extras)
    require_cloudflare_credentials(settings)
    remote_note = ""
    cloudflare_error = ""
    try:
        if settings.remote_access == "cloudflare" and settings.cloudflare_api_token:
            print("Setting up the Cloudflare tunnel...")
            remote_note = provision_cloudflare(settings)
        elif settings.remote_access == "cloudflare":
            remote_note = tunnel_token_note(settings)
    except SetupError as error:
        cloudflare_error = str(error)
        remote_note = cloudflare_error
    finally:
        write_env_file(ENV_PATH, settings, extras)
    prepare_directories(settings)
    gluetun_names = [key.removeprefix("GLUETUN_") for key in extras]
    use_tunnel = settings.remote_access == "cloudflare" and bool(settings.cloudflare_tunnel_token)
    (ROOT / "docker-compose.yml").write_text(
        render_compose(True, gluetun_names, cloudflare=use_tunnel),
        encoding="utf-8",
    )
    (ROOT / "docker-compose.novpn.yml").write_text(
        render_compose(False, cloudflare=use_tunnel),
        encoding="utf-8",
    )
    if not configure_only:
        print("Starting containers..." if repair else "Starting anything that is not running yet...")
        compose_up(settings.vpn_enabled)
    elif use_tunnel:
        print("Starting the Cloudflare tunnel...")
        compose_up(settings.vpn_enabled, services=["cloudflared"])
    configurator = StackConfigurator(
        settings,
        restarter=lambda service: restart_service(service, settings.vpn_enabled),
    )
    if repair:
        configurator.configure()
    else:
        print("Left the existing app settings in place.")
        print("Answer yes to the check next time when you want those accounts linked.")
    if settings.remote_access == "forward":
        print("Opening Jellyfin and Requests on the router...")
        remote_note = forward_ports(settings)
        write_env_file(ENV_PATH, settings, extras)
    elif settings.remote_access == "tailscale":
        print("Connecting Tailscale...")
        remote_note = setup_tailscale(settings)
        write_env_file(ENV_PATH, settings, extras)
    elif settings.remote_access == "lan":
        print("Opening Jellyfin and Seerr on the home network...")
        remote_note = setup_lan(settings)
        write_env_file(ENV_PATH, settings, extras)
    if repair and (settings.public_jellyfin_url or settings.public_seerr_url):
        try:
            configurator.publish_remote_urls()
        except SetupError as error:
            remote_note += (
                f"\n\nSeerr did not save the public address ({error}). "
                "Jellyfin can still use the address above. Rerun ./install.sh once Seerr is up."
            )
    print()
    if repair:
        write_credentials(settings, configurator.api_keys, remote_note)
        print(CREDENTIALS_PATH.read_text(encoding="utf-8"))
        print(f"Saved to {CREDENTIALS_PATH}")
    elif CREDENTIALS_PATH.exists():
        print(CREDENTIALS_PATH.read_text(encoding="utf-8"))
        print(f"Saved to {CREDENTIALS_PATH}")
        if remote_note.strip():
            print(remote_note.strip())
    else:
        print("Accounts were not created. Rerun the command and answer yes to the config check.")
        if remote_note.strip():
            print(remote_note.strip())
    guide = build_lan_access_guide(settings)
    print()
    print(guide)
    if CREDENTIALS_PATH.exists():
        current = CREDENTIALS_PATH.read_text(encoding="utf-8")
        if "Home network address" not in current:
            CREDENTIALS_PATH.write_text(current.rstrip() + "\n\n" + guide + "\n", encoding="utf-8")
            os.chmod(CREDENTIALS_PATH, 0o600)
    if cloudflare_error:
        raise SetupError(cloudflare_error)
    if use_tunnel:
        wait_for_cloudflared(settings)


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="install.sh",
        description="Install and configure the automated Jellyfin stack.",
    )
    parser.add_argument("--yes", action="store_true", help="Accept defaults and environment variables without prompting.")
    parser.add_argument("--no-vpn", action="store_true", help="Do not route downloads through Gluetun.")
    parser.add_argument(
        "--remote",
        help="Where to watch: lan (this Wi-Fi), cloudflare, forward, tailscale, or local. Asked when omitted.",
    )
    parser.add_argument("--configure-only", action="store_true", help="Skip docker compose and only configure running apps.")
    parser.add_argument("--render-only", action="store_true", help="Write compose files and exit.")
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Print the install plan. Do not install Docker, pull images, or download media.",
    )
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    try:
        if args.dry_run:
            script = ROOT / "script.sh"
            subprocess.run(["bash", str(script)], check=True)
            print("Dry run finished. No packages, images, or media were downloaded.")
            return 0
        if args.render_only:
            (ROOT / "docker-compose.yml").write_text(render_compose(True), encoding="utf-8")
            (ROOT / "docker-compose.novpn.yml").write_text(render_compose(False), encoding="utf-8")
            return 0
        install(
            assume_yes=args.yes,
            no_vpn=args.no_vpn,
            configure_only=args.configure_only,
            remote=args.remote,
        )
    except SetupError as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    except subprocess.CalledProcessError as error:
        hint = ""
        if "compose" in error.cmd:
            hint = (
                "\n\nDocker did not start the containers. Read the Docker lines above.\n"
                "If they say the port is already in use, change that port in .env and rerun ./install.sh.\n"
                "If they say permission denied, rerun ./install.sh so it can use sudo for Docker."
            )
        print(f"error: command failed ({error.returncode}): {' '.join(error.cmd)}{hint}", file=sys.stderr)
        return error.returncode or 1
    except KeyboardInterrupt:
        print("\nStopped.", file=sys.stderr)
        return 130
    return 0


if __name__ == "__main__":
    sys.exit(main())
